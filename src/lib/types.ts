/**
 * Domain types for the simulation-debrief prototype.
 *
 * The whole app is organised around PROVENANCE: every piece of information
 * shown belongs to exactly one tier:
 *   - "source"     raw events received from the simulator (ground truth)
 *   - "calculated" facts derived deterministically from source events
 *   - "ai"         generated, advisory suggestions (pre-baked in this prototype)
 *
 * The schema is deliberately extensible: future data streams (vitals, CPR
 * quality, movement, comms, instructor notes) are optional and additive, so a
 * case can include or omit any of them and the UI degrades gracefully.
 */

export type ProvenanceTier = "source" | "calculated" | "ai";

/** Rule-of-thumb status for a calculated metric. NOT clinical guidance. */
export type FlagStatus = "good" | "warn" | "neutral";

// --- Source data ------------------------------------------------------------

export interface Session {
  id: string;
  durationSeconds: number;
  title?: string; // human label for the case, e.g. "Adult VF arrest, textbook"
  scenarioType?: string; // e.g. "Adult ALS: VF cardiac arrest"
  date?: string; // ISO YYYY-MM-DD, when the session was run (for chronology)
}

/**
 * A learner whose sessions are reviewed over time. In production this sits under
 * a roster; here there is one mock student. `aiProgression` is a pre-baked,
 * AI-tier summary of how the learner is trending across their sessions.
 */
export interface Student {
  id: string;
  name: string;
  descriptor: string; // e.g. "Paramedic trainee"
  sessionIds: string[]; // chronological (oldest → newest)
  aiProgression: string;
}

export interface Participant {
  id: string;
  role: string; // "Team Leader" | "Airway" | "Nurse" | "Runner" | ...
}

/**
 * Known event types for an ALS cardiac-arrest scenario. The union stays open
 * (`string & {}`) so future/unknown event types are accepted without a schema
 * change while known ones still autocomplete.
 */
export const KNOWN_EVENT_TYPES = [
  "Scenario Started",
  "Ventricular Fibrillation",
  "Pulseless VT",
  "Asystole",
  "PEA",
  "CPR Started",
  "CPR Paused",
  "Rhythm Check",
  "Shock Delivered",
  "Adrenaline Given",
  "Amiodarone Given",
  "Return of Spontaneous Circulation",
  "Re-arrest",
  "Scenario Finished",
] as const;

export type KnownEventType = (typeof KNOWN_EVENT_TYPES)[number];
// eslint-disable-next-line @typescript-eslint/ban-types
export type EventType = KnownEventType | (string & {});

export interface SimEvent {
  /** Seconds elapsed from scenario start. */
  time: number;
  type: EventType;
  /** Optional: which participant performed/triggered it (future-friendly). */
  participantId?: string;
  /** Optional free-text detail (e.g. "200J biphasic"). */
  detail?: string;
}

// --- Future data streams (all optional, all additive) -----------------------

export interface VitalSample {
  time: number;
  heartRate?: number;
  spo2?: number;
  systolic?: number;
  diastolic?: number;
  etco2?: number;
}

export interface CprQualitySample {
  time: number;
  rate?: number; // compressions per minute
  depthMm?: number;
  fullRecoil?: boolean;
}

export interface InstructorNote {
  time?: number; // optional, some notes are session-wide
  author?: string;
  text: string;
}

// --- The case payload -------------------------------------------------------

export interface SessionData {
  session: Session;
  participants: Participant[];
  events: SimEvent[];

  // Future streams: a case may include none, some, or all of these.
  vitals?: VitalSample[];
  cprQuality?: CprQualitySample[];
  instructorNotes?: InstructorNote[];

  /**
   * Pre-baked AI output for this case. In production this would be generated by
   * a model from the source events + calculated facts; here it is hand-authored
   * and clearly tagged as the "ai" tier. See `AiDebrief`.
   */
  ai?: AiDebrief;
}

// --- Calculated tier --------------------------------------------------------

export interface Metric {
  id: string;
  label: string;
  tier: "calculated";
  /** Raw machine value (seconds, count, or boolean). null = not applicable. */
  value: number | boolean | null;
  /** Human-readable rendering, e.g. "0:17", "73s", "Yes". */
  display: string;
  /** Rule-of-thumb flag. Only set where a defensible heuristic exists. */
  status: FlagStatus;
  /** One-line, plain-language reason for the flag (rule-of-thumb, not advice). */
  note?: string;
  /**
   * The source events this fact was derived from, as "Type@mm:ss" strings.
   * Powers the "derived from …" provenance trail in the UI.
   */
  derivedFrom: string[];
}

export interface DerivedFacts {
  metrics: Metric[];
  /** True if a Return of Spontaneous Circulation event occurred. */
  roscAchieved: boolean;
}

// --- AI tier ----------------------------------------------------------------

export interface AiDiscussionPoint {
  text: string;
  /** Optional: ties the suggestion to a moment, for "jump to" affordances. */
  atTime?: number;
}

export interface AiMomentToReview {
  time: number;
  reason: string;
}

export interface AiDebrief {
  summary: string;
  discussionPoints: AiDiscussionPoint[];
  momentsToReview: AiMomentToReview[];
  /** Always true here: a reminder this content is generated/advisory. */
  generated: true;
}
